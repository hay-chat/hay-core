import { TRPCError } from "@trpc/server";
import { t } from "@server/trpc/init";
import * as jwt from "jsonwebtoken";
import type { Context } from "@server/trpc/context";
import {
  isOrganizationOpenToPlugins,
  PluginApiTokenClaimsError,
  verifyPluginApiToken,
} from "@server/lib/plugin-api-token";
import { organizationRepository } from "@server/repositories/organization.repository";

/**
 * Extended context with plugin authentication
 */
export interface PluginAuthContext extends Context {
  pluginAuth: {
    organizationId: string;
    pluginId: string;
    capabilities: string[];
  };
}

/**
 * Middleware to verify plugin JWT token
 *
 * Plugins authenticate using JWT tokens generated by the plugin manager.
 * The token contains:
 * - organizationId: Organization ID this plugin instance belongs to
 * - pluginId: Plugin identifier
 * - scope: Must be "plugin-api"
 * - capabilities: Array of capabilities (routes, messages, customers, sources, mcp)
 *
 * Issuer, audience and scope are checked by the shared verifier, and the
 * organization must exist, be active and not be suspended.
 */
export const verifyPluginAuth = t.middleware(async ({ ctx, next }) => {
  // Extract token from Authorization header
  const authHeader = ctx.req.headers.authorization;

  if (!authHeader) {
    throw new TRPCError({
      code: "UNAUTHORIZED",
      message: "No authorization header provided",
    });
  }

  const token = authHeader.replace("Bearer ", "");

  if (!token) {
    throw new TRPCError({
      code: "UNAUTHORIZED",
      message: "No token provided",
    });
  }

  let decoded;
  try {
    decoded = verifyPluginApiToken(token);
  } catch (error) {
    if (error instanceof jwt.TokenExpiredError) {
      throw new TRPCError({
        code: "UNAUTHORIZED",
        message: "Token has expired",
      });
    }

    if (error instanceof jwt.JsonWebTokenError) {
      throw new TRPCError({
        code: "UNAUTHORIZED",
        message: "Invalid token",
      });
    }

    if (error instanceof PluginApiTokenClaimsError) {
      throw new TRPCError({
        code: "FORBIDDEN",
        message: error.message,
      });
    }

    throw new TRPCError({
      code: "INTERNAL_SERVER_ERROR",
      message: "Failed to verify token",
    });
  }

  const organization = await organizationRepository.findById(decoded.organizationId);
  if (!isOrganizationOpenToPlugins(organization)) {
    throw new TRPCError({
      code: "FORBIDDEN",
      message: "Organization is not available",
    });
  }

  // Add plugin auth to context
  return next({
    ctx: {
      ...ctx,
      pluginAuth: {
        organizationId: decoded.organizationId,
        pluginId: decoded.pluginId,
        capabilities: decoded.capabilities,
      },
    } as PluginAuthContext,
  });
});

/**
 * Plugin procedure with authentication
 */
export const pluginProcedure = t.procedure.use(verifyPluginAuth);

/**
 * Helper to check if a capability is present
 */
export function requireCapability(ctx: PluginAuthContext, capability: string): void {
  if (!ctx.pluginAuth.capabilities.includes(capability)) {
    throw new TRPCError({
      code: "FORBIDDEN",
      message: `Plugin does not have '${capability}' capability`,
    });
  }
}
