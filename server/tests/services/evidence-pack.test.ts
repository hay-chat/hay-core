/**
 * D2-5: the evidence ZIP (PDF, attachments, README, SHA-256 manifest) and the
 * order total/date read from a tool answer.
 */
import { describe, it, expect } from "@jest/globals";
import { createHash } from "crypto";
import AdmZip from "adm-zip";
import { buildEvidenceZip } from "../../services/dispute-evidence/evidence-zip";
import { orderSummaryFrom } from "../../services/dispute-evidence/order-summary";
import type { EvidenceResult } from "../../services/dispute-evidence/dispute-evidence.service";

describe("buildEvidenceZip", () => {
  it("packs the PDF, attachments and an honest README with a SHA-256 manifest", async () => {
    const pdf = Buffer.from("%PDF-1.3 test");
    const photo = Buffer.from("jpeg-bytes");
    const result: EvidenceResult = {
      pdf,
      locale: "en",
      overCap: false,
      imagesOmitted: false,
      attachments: [
        {
          conversationId: "c1",
          attachment: { id: "u1", name: "../box photo.jpg", url: "", type: "image/jpeg", size: 10 },
          buffer: photo,
          mimeType: "image/jpeg",
        },
      ],
      conversationIds: ["c1"],
      storeName: "Example Store",
      generatedAt: new Date("2026-10-20T12:00:00Z"),
    };
    const zip = new AdmZip(
      await buildEvidenceZip(result, { timeZone: "UTC", template: "generic", orderLabel: "#1001" }),
    );
    const names = zip.getEntries().map((e) => e.entryName);
    expect(names).toEqual([
      "evidence.pdf",
      "attachments/01-box_photo.jpg",
      "README.txt",
      "manifest.json",
    ]);
    const manifest = JSON.parse(zip.readAsText("manifest.json"));
    expect(manifest.generatedBy).toBe("Hay.chat");
    expect(manifest.order).toBe("#1001");
    for (const file of manifest.files) {
      const data = zip.readFile(file.path)!;
      expect(createHash("sha256").update(data).digest("hex")).toBe(file.sha256);
    }
    const readme = zip.readAsText("README.txt");
    expect(readme).toContain(
      "Generated by Hay.chat on 2026-10-20 12:00:00 UTC+00:00 for Example Store.",
    );
    expect(readme).toContain("does not guarantee any outcome");
  });
});

describe("orderSummaryFrom", () => {
  const tokens = new Set(["5566", "1001"]);
  it("reads total and date from the matching order", () => {
    const output = {
      content: [
        {
          type: "text",
          text: JSON.stringify({
            id: "gid://s/Order/5566",
            name: "#1001",
            createdAt: "2026-09-30T10:00:00Z",
            totalPriceSet: { shopMoney: { amount: "120.00", currencyCode: "EUR" } },
          }),
        },
      ],
    };
    expect(orderSummaryFrom(output, tokens)).toEqual({
      total: "120.00 EUR",
      placedAt: "2026-09-30T10:00:00Z",
    });
  });

  it("ignores other orders", () => {
    expect(orderSummaryFrom({ id: 9, number: 9, total: "5.00" }, tokens)).toBeNull();
    expect(
      orderSummaryFrom({ orders: [{ id: 5566, total: "9.90", currency: "BRL" }] }, tokens),
    ).toEqual({ total: "9.90 BRL", placedAt: null });
  });
});
